def main() -> None:
    tables = {"zh-Hans": {}, "en": {}, "zh-Hant": {}, "ja": {}}
    seen = set()
    for key, en, hant, ja in ROWS:
        if key in seen:
            raise SystemExit(f"duplicate key: {key}")
        seen.add(key)
        tables["zh-Hans"][key] = key
        tables["en"][key] = en
        tables["zh-Hant"][key] = hant
        tables["ja"][key] = ja
    root = Path(__file__).resolve().parents[1]
    destination = root / "QuickDoc" / "Resources" / "QuickDocLocalizable.json"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(tables, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {len(seen)} keys to {destination}")


